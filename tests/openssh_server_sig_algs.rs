//! Opt-in live regression lane for RFC 8308 `server-sig-algs`.
//!
//! Run explicitly with:
//!
//! ```text
//! NEOTALES_SSH_E2E=1 cargo test -p neotales-ssh --test openssh_server_sig_algs \
//!     -- --ignored --test-threads=1
//! ```
//!
//! # What this lane is for
//!
//! `server-sig-algs` is the extension that tells a client which user-auth
//! signature algorithms a server will accept for a public key. It is easy to
//! test against an in-process peer, and this crate already does that in
//! `auth_algorithms.rs`. What an in-process peer cannot prove is that a *real*
//! OpenSSH server accepts what this client sends after reading the list, or
//! that the list it reads is the one OpenSSH meant to send.
//!
//! The server below is a throwaway loopback `sshd` restricted with
//! `PubkeyAcceptedAlgorithms rsa-sha2-256`. OpenSSH derives the advertised
//! `server-sig-algs` value from that option, so the peer advertises and accepts
//! exactly one RSA user-auth signature algorithm. `sshd -T` is checked before
//! the lane proceeds, because a typo in the option name would otherwise leave a
//! permissive server that proves nothing.
//!
//! # Why the identity is explicitly SHA-512
//!
//! This crate's default RSA identity already is `rsa-sha2-256`, so a default
//! signer cannot show whether the client reads the advertisement: both with and
//! without `ext-info-c` it would send the one algorithm the server accepts.
//! The lane therefore uses an explicitly selected [`PublicKeySigner::rsa_sha512`]
//! identity. That signer starts out preferring `rsa-sha2-512`, so the two cases
//! become a real contrast in which a client that ignores the peer's list loses.
//! It is not a claim about the crate's default, and it does not rely on one.
//!
//! # Both directions
//!
//! * Case A opts into `ext-info-c` with [`ClientConfig::with_extension_info`].
//!   The client records the peer's list, must select the only entry,
//!   `rsa-sha2-256`, and authenticate. The evidence is the *server's* log: it
//!   names the algorithm the client actually offered
//!   (`userauth_pubkey: ... pkalg rsa-sha2-256`), records the acceptance, and
//!   contains no `rsa-sha2-512` offer at all. A client-side counter cannot
//!   prove the peer read or accepted anything.
//! * Case B uses the same server and the same SHA-512 identity without
//!   `ext-info-c`. Without the peer's list the client has no reason to move off
//!   its preference, so it offers `rsa-sha2-512`, and the restricted server
//!   refuses it. This is the regression that matters: RFC 8308 exists so an RSA
//!   client does not guess a signature algorithm a modern server has disabled.
//!
//! # Runtime prerequisites
//!
//! `sshd` and `ssh-keygen` are the system OpenSSH programs, resolved at run
//! time by `openssh_tools` rather than named by absolute path. Without
//! `NEOTALES_SSH_E2E=1` all tests return before creating a directory or
//! starting a process. With it set, a missing program is a failure: these lanes
//! are evidence, and a lane that reported success because it never started a
//! peer would make the evidence unfalsifiable.
//!
//! There is no Docker, no network beyond loopback, no host account, and no
//! credential. The host key and the RSA user key are generated by `ssh-keygen`
//! inside a private temporary directory and removed with it.

mod openssh_tools;

use std::error::Error;
use std::fs;
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use neotales_ssh::ClientConfig;
use neotales_ssh::auth::{AuthMethodKind, ClientAuthMethod, PublicKeySigner, authenticate_client};
use neotales_ssh::openssh_key::OpenSshPrivateKey;
use neotales_ssh::transport::ClientTransport;

/// How long a lane waits for the peer before calling it a failure.
const LANE_DEADLINE: Duration = Duration::from_secs(15);

/// The only user-auth signature algorithm the throwaway server advertises and
/// accepts.
const ACCEPTED_RSA_SIGNATURE: &str = "rsa-sha2-256";

/// The throwaway server's private state, removed when the lane finishes.
struct OpenSshServer {
    _child: openssh_tools::temp_dir::ChildGuard,
    directory: openssh_tools::temp_dir::TempDir,
    port: u16,
    log: PathBuf,
}

/// Returns whether the live lane was requested.
///
/// The `#[ignore]` attribute keeps these tests out of the default run. When the
/// caller asks for them with `NEOTALES_SSH_E2E=1`, every prerequisite below is
/// an error rather than a skip.
fn live_lane_requested() -> bool {
    if std::env::var("NEOTALES_SSH_E2E").as_deref() == Ok("1") {
        true
    } else {
        eprintln!("skipping live OpenSSH server-sig-algs lane: set NEOTALES_SSH_E2E=1");
        false
    }
}

/// Runs `ssh-keygen` for one throwaway key, failing if it refuses.
fn generate_key(ssh_keygen: &Path, kind: &str, path: &Path) -> Result<(), Box<dyn Error>> {
    let generated = Command::new(ssh_keygen)
        .args(["-q", "-t", kind, "-N", "", "-f"])
        .arg(path)
        .stdout(Stdio::null())
        .stderr(Stdio::inherit())
        .output()
        .map_err(|error| {
            format!(
                "failed to run ssh-keygen at {}: {error}",
                ssh_keygen.display()
            )
        })?;
    if !generated.status.success() {
        return Err(format!(
            "ssh-keygen could not create the throwaway {kind} key at {}",
            path.display()
        )
        .into());
    }
    Ok(())
}

/// Reads the effective server configuration back through `sshd -T`.
///
/// The restriction is the premise of the whole lane. If this option were
/// misspelled or unsupported the server would fall back to its defaults and
/// both cases would pass without testing anything, so the lane checks the
/// parsed configuration instead of trusting the file it wrote.
fn effective_config(sshd: &Path, config: &Path) -> Result<String, Box<dyn Error>> {
    let checked = Command::new(sshd)
        .args(["-T", "-f"])
        .arg(config)
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .output()
        .map_err(|error| format!("failed to run sshd -T at {}: {error}", sshd.display()))?;
    if !checked.status.success() {
        return Err("sshd -T refused the throwaway configuration".into());
    }
    Ok(String::from_utf8_lossy(&checked.stdout).into_owned())
}

/// Starts a loopback-only server that advertises and accepts only
/// [`ACCEPTED_RSA_SIGNATURE`].
fn start_server() -> Result<OpenSshServer, Box<dyn Error>> {
    start_server_with_rekey(false)
}

fn start_server_with_rekey(rekey: bool) -> Result<OpenSshServer, Box<dyn Error>> {
    let directory = openssh_tools::temp_dir::TempDir::new("neotales-server-sig-algs")
        .map_err(|error| format!("could not create the server-sig-algs test directory: {error}"))?;
    let ssh_keygen = openssh_tools::ssh_keygen()?;
    let sshd = openssh_tools::sshd()?;

    let host_key = directory.join("host_ed25519");
    generate_key(&ssh_keygen, "ed25519", &host_key)?;
    // The user key has to be RSA: `server-sig-algs` is only meaningful for RSA
    // user authentication, where one key type has several signature encodings.
    let user_key = directory.join("id_rsa");
    generate_key(&ssh_keygen, "rsa", &user_key)?;

    let listener = std::net::TcpListener::bind(("127.0.0.1", 0))?;
    let port = listener.local_addr()?.port();
    drop(listener);

    let config = directory.join("sshd_config");
    fs::write(
        &config,
        format!(
            "Port {port}\n\
             ListenAddress 127.0.0.1\n\
             HostKey {}\n\
             PidFile {}\n\
             UsePAM no\n\
             UseDNS no\n\
             PasswordAuthentication no\n\
             KbdInteractiveAuthentication no\n\
             ChallengeResponseAuthentication no\n\
             PubkeyAuthentication yes\n\
             AuthorizedKeysFile {}\n\
             PermitRootLogin no\n\
             StrictModes no\n\
             MaxAuthTries 100\n\
             LoginGraceTime 60\n\
             LogLevel {}\n\
             PubkeyAcceptedAlgorithms {ACCEPTED_RSA_SIGNATURE}\n\
             {}\n",
            host_key.display(),
            directory.join("sshd.pid").display(),
            user_key.with_extension("pub").display(),
            if rekey { "DEBUG3" } else { "DEBUG1" },
            if rekey { "RekeyLimit 64K 1h" } else { "" },
        ),
    )
    .map_err(|error| {
        format!(
            "could not write the sshd configuration under {}: {error}",
            directory.display()
        )
    })?;

    let effective = effective_config(&sshd, &config)?;
    if rekey
        && !effective
            .lines()
            .any(|line| line.eq_ignore_ascii_case("rekeylimit 65536 3600"))
    {
        return Err(format!("sshd did not apply RekeyLimit: {effective}").into());
    }
    let expected = format!("pubkeyacceptedalgorithms {ACCEPTED_RSA_SIGNATURE}");
    if !effective.lines().any(|line| {
        line.split_whitespace()
            .map(str::to_ascii_lowercase)
            .collect::<Vec<_>>()
            .join(" ")
            == expected
    }) {
        return Err(format!(
            "the throwaway sshd did not apply the restriction: expected a line `{expected}` in \
             its effective configuration"
        )
        .into());
    }

    // `-E` writes the peer's own log to a file. The server's record of which
    // algorithm the client offered is the evidence for both cases, and it is
    // not visible to the client that produced the offer.
    let log = directory.join("sshd.log");
    let mut command = Command::new(&sshd);
    command
        .args(["-D", "-E"])
        .arg(&log)
        .args(["-f"])
        .arg(&config)
        .stdout(Stdio::null())
        .stderr(Stdio::inherit());
    let mut child = openssh_tools::temp_dir::ChildGuard::spawn_tree(&mut command)
        .map_err(|error| format!("failed to run sshd at {}: {error}", sshd.display()))?;

    let deadline = Instant::now() + LANE_DEADLINE;
    loop {
        if TcpStream::connect(("127.0.0.1", port)).is_ok() {
            return Ok(OpenSshServer {
                _child: child,
                directory,
                port,
                log,
            });
        }
        if let Some(status) = child.try_wait()? {
            return Err(
                format!("the throwaway sshd exited before becoming reachable: {status}").into(),
            );
        }
        if Instant::now() > deadline {
            return Err("the throwaway sshd did not become reachable".into());
        }
        std::thread::sleep(Duration::from_millis(25));
    }
}

/// Exchanges patterned bytes through `cat` in small chunks, so both directions
/// cross the server's byte limit without deadlocking the channel windows.
/// OpenSSH's second NEWKEYS proves a rekey beyond the initial handshake, and
/// the second channel proves the same connection remains usable afterwards.
#[test]
#[ignore = "live OpenSSH rekey lane: NEOTALES_SSH_E2E=1"]
fn live_openssh_rekeys_during_bidirectional_channel_traffic() -> Result<(), Box<dyn Error>> {
    use neotales_ssh::session::{ClientSessions, SessionEvent};

    if !live_lane_requested() {
        return Ok(());
    }
    let server = start_server_with_rekey(true)?;
    let result = (|| -> Result<(), Box<dyn Error>> {
        let signer = sha512_rsa_signer(&server.directory)?;
        let mut transport = connect(server.port, true)?;
        authenticate_client(
            &mut transport,
            openssh_tools::current_user()?,
            &[ClientAuthMethod::public_key(signer)],
            4,
        )?;
        let mut sessions = ClientSessions::new(transport);
        for size in [256 * 1024, 4096] {
            let id = sessions.open_session()?;
            while !matches!(sessions.dispatch_one()?, SessionEvent::Opened { session } if session == id)
            {
            }
            sessions.request_exec(id, b"cat", true)?;
            let data: Vec<u8> = (0..size)
                .map(|i| u8::try_from((i * 31 + i / 251) % 256).unwrap())
                .collect();
            let mut received = Vec::new();
            for chunk in data.chunks(4096) {
                while sessions
                    .connection()
                    .channel(id)
                    .ok_or("missing channel")?
                    .remote_window()
                    < 4096
                {
                    sessions.dispatch_one()?;
                }
                let target = received.len() + chunk.len();
                let written = sessions.send_data(id, chunk)?;
                assert_eq!(written, chunk.len());
                while received.len() < target {
                    match sessions.dispatch_one()? {
                        SessionEvent::Data { session, data } if session == id => {
                            sessions.increase_local_window(id, u32::try_from(data.len())?)?;
                            received.extend(data);
                        }
                        SessionEvent::Close { .. } => return Err("cat closed early".into()),
                        _ => {}
                    }
                }
            }
            sessions.send_eof(id)?;
            while !matches!(sessions.dispatch_one()?, SessionEvent::Close { session } if session == id)
            {
            }
            assert_eq!(received, data);
        }
        Ok(())
    })();
    let log = fs::read_to_string(&server.log).unwrap_or_default();
    if let Err(error) = result {
        return Err(format!("rekey traffic failed: {error}\nsshd log:\n{log}").into());
    }
    assert!(
        log.matches("SSH2_MSG_NEWKEYS sent").count() >= 2,
        "no peer rekey:\n{log}"
    );
    Ok(())
}

/// Decodes the base64 body of an armored `ssh-keygen` private key.
fn base64_decode(input: &str) -> Result<Vec<u8>, Box<dyn Error>> {
    const TABLE: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = Vec::new();
    let mut accumulator: u32 = 0;
    let mut bits: u32 = 0;
    for byte in input.bytes() {
        if byte == b'=' || byte.is_ascii_whitespace() {
            continue;
        }
        let value = TABLE
            .iter()
            .position(|candidate| *candidate == byte)
            .ok_or("invalid base64 in the generated key")?;
        let value = u32::try_from(value).expect("a base64 index fits a u32");
        accumulator = (accumulator << 6) | value;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push(((accumulator >> bits) & 0xff) as u8);
        }
    }
    Ok(out)
}

/// Parses the generated RSA private key with this crate's own container reader.
fn parse_user_key(directory: &Path) -> Result<OpenSshPrivateKey, Box<dyn Error>> {
    let text = fs::read_to_string(directory.join("id_rsa"))?;
    let body: String = text
        .lines()
        .filter(|line| !line.starts_with("-----") && !line.starts_with("Private-key"))
        .collect();
    let decoded = base64_decode(body.trim())?;
    let mut passphrase: [u8; 0] = [];
    Ok(OpenSshPrivateKey::parse(&decoded, &mut passphrase)?)
}

/// Connects, optionally asking for RFC 8308 extension negotiation.
fn connect(port: u16, extension_info: bool) -> Result<ClientTransport<TcpStream>, Box<dyn Error>> {
    let stream = TcpStream::connect(("127.0.0.1", port))?;
    stream.set_read_timeout(Some(LANE_DEADLINE))?;
    stream.set_write_timeout(Some(LANE_DEADLINE))?;
    let config = if extension_info {
        ClientConfig::new().with_extension_info()
    } else {
        ClientConfig::new()
    };
    Ok(config.connect(stream, |_key| Ok::<(), ()>(()))?)
}

/// An explicit SHA-512 RSA identity for a key this crate parsed itself.
///
/// The algorithm is selected explicitly so the lane tests the client's handling
/// of the peer's list. The crate's default `PublicKeySigner::rsa` is already
/// `rsa-sha2-256`, which would satisfy this server with or without `ext-info-c`
/// and prove nothing about the advertisement. This signer prefers
/// `rsa-sha2-512`, which is exactly the offer a client must abandon when the
/// peer says it accepts only `rsa-sha2-256`.
fn sha512_rsa_signer(directory: &Path) -> Result<PublicKeySigner, Box<dyn Error>> {
    let parsed = parse_user_key(directory)?;
    let OpenSshPrivateKey::Rsa { p, q, e, .. } = parsed else {
        return Err("ssh-keygen produced something other than an RSA key".into());
    };
    let signer = neotales_ssh::auth::RsaAuthSigner::from_p_q(
        rsa::BigUint::from_bytes_be(&p),
        rsa::BigUint::from_bytes_be(&q),
        rsa::BigUint::from_bytes_be(&e),
    )?;
    Ok(PublicKeySigner::rsa_sha512(signer))
}

/// Reads the peer log until any of `wanted` appears, or the deadline expires.
fn wait_for_log(server: &OpenSshServer, wanted: &[&str]) -> Result<String, Box<dyn Error>> {
    let deadline = Instant::now() + LANE_DEADLINE;
    loop {
        let log = fs::read_to_string(&server.log).unwrap_or_default();
        if wanted.iter().any(|needle| log.contains(needle)) || Instant::now() > deadline {
            return Ok(log);
        }
        std::thread::sleep(Duration::from_millis(25));
    }
}

/// Case A: with `ext-info-c`, an RSA identity that prefers `rsa-sha2-512`
/// abandons it for the peer's advertised algorithm and authenticates.
///
/// The assertion that counts is the server's log: it names
/// `pkalg rsa-sha2-256`, records the acceptance, and contains no
/// `rsa-sha2-512` offer. A client that never read the list would have offered
/// SHA-512, which this server refuses -- that is Case B.
#[test]
#[ignore = "live OpenSSH server-sig-algs lane: NEOTALES_SSH_E2E=1"]
fn live_openssh_server_sig_algs_accepts_the_advertised_algorithm() -> Result<(), Box<dyn Error>> {
    if !live_lane_requested() {
        return Ok(());
    }
    let server = start_server()?;
    let signer = sha512_rsa_signer(&server.directory)?;

    let mut transport = connect(server.port, true)?;
    let success = authenticate_client(
        &mut transport,
        openssh_tools::current_user()?,
        &[ClientAuthMethod::public_key(signer)],
        4,
    )?;
    assert_eq!(success.method(), AuthMethodKind::PublicKey);

    // The list is recorded while the authenticator drains the handshake's
    // extension message, so it is only readable after authentication. It is a
    // sanity check on what the client recorded, not the evidence: the peer log
    // below is.
    let advertised = transport
        .server_signature_algorithms()
        .ok_or("the client did not record a server-sig-algs list")?
        .to_vec();
    assert_eq!(
        advertised,
        [ACCEPTED_RSA_SIGNATURE.to_owned()],
        "the throwaway server advertised something other than its restriction"
    );

    // Peer evidence, not a client counter: OpenSSH logs the algorithm of the
    // key it tested and the acceptance it granted.
    let log = wait_for_log(&server, &["Accepted publickey", "pkalg rsa-sha2-512"])?;
    assert!(
        log.contains(&format!("pkalg {ACCEPTED_RSA_SIGNATURE}")),
        "the server log does not show it received {ACCEPTED_RSA_SIGNATURE}:\n{log}"
    );
    assert!(
        !log.contains("pkalg rsa-sha2-512"),
        "the client offered rsa-sha2-512 even though the peer advertised only \
         {ACCEPTED_RSA_SIGNATURE}:\n{log}"
    );
    assert!(
        log.contains("Accepted publickey"),
        "the server log does not show a completed public-key authentication:\n{log}"
    );
    Ok(())
}

/// Case B: the same SHA-512-preferring identity without `ext-info-c` offers
/// `rsa-sha2-512`, and this server accepts only `rsa-sha2-256`.
///
/// The peer must refuse the offer and say so in its log. If the client
/// authenticated here, it sent an algorithm the server had disabled, which is
/// exactly the failure `server-sig-algs` exists to prevent.
#[test]
#[ignore = "live OpenSSH server-sig-algs lane: NEOTALES_SSH_E2E=1"]
fn live_openssh_server_sig_algs_refuses_the_unadvertised_sha512_offer() -> Result<(), Box<dyn Error>>
{
    if !live_lane_requested() {
        return Ok(());
    }
    let server = start_server()?;
    let signer = sha512_rsa_signer(&server.directory)?;

    let mut transport = connect(server.port, false)?;
    assert!(
        transport.server_signature_algorithms().is_none(),
        "ext-info was negotiated even though ext-info-c was not offered"
    );
    let result = authenticate_client(
        &mut transport,
        openssh_tools::current_user()?,
        &[ClientAuthMethod::public_key(signer)],
        4,
    );

    let log = wait_for_log(
        &server,
        &[
            "Accepted publickey",
            "signature algorithm rsa-sha2-512 not in PubkeyAcceptedAlgorithms",
        ],
    )?;
    assert!(
        result.is_err(),
        "the client authenticated without reading server-sig-algs, so it sent an algorithm the \
         server had disabled. Peer log:\n{log}"
    );
    assert!(
        log.contains("signature algorithm rsa-sha2-512 not in PubkeyAcceptedAlgorithms"),
        "the server log does not show the unadvertised rsa-sha2-512 offer being refused:\n{log}"
    );
    assert!(
        !log.contains("Accepted publickey"),
        "the server log shows an accepted public key even though the only offer was \
         rsa-sha2-512:\n{log}"
    );
    Ok(())
}
